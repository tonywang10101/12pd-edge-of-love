// Short, original prose. Required scene facts are never cut to meet a length limit.
export const narrativeLength = text => [...String(text).replace(/\s/g,'')].length;
export function composeNarrative(core, additions = [], context = '') {
  let text=[context,core].filter(Boolean).join('\n\n');
  for(const paragraph of additions){
    if(paragraph && narrativeLength(text+'\n\n'+paragraph)<=150)text+='\n\n'+paragraph;
  }
  return text;
}
export function makeNarration(id,number,core){
  return {text:core,narrativeCore:core,narrativeAdditions:[]};
}
